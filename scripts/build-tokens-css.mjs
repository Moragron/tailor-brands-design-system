// tokens/tokens.json (source of truth) -> tokens/tokens.css (CSS custom properties).
// Each property carries a trailing comment saying whether it was observed and where from.
import { readFileSync, writeFileSync } from 'node:fs';

const jsonPath = process.env.TB_TOKENS_JSON ?? new URL('../tokens/tokens.json', import.meta.url).pathname;
const tokens = JSON.parse(readFileSync(jsonPath, 'utf8'));
const lines = [];

function walk(node, path) {
  for (const [key, val] of Object.entries(node)) {
    if (key.startsWith('$') || typeof val !== 'object' || val === null) continue;
    if ('$value' in val) {
      const name = `--tb-${[...path, key].join('-')}`;
      const provenance = val.$observed ? `observed: ${val.$source}` : 'PLACEHOLDER — not observed';
      lines.push(`  ${name}: ${val.$value}; /* ${provenance} */`);
    } else {
      walk(val, [...path, key]);
    }
  }
}
walk(tokens, []);

const header = `/*
 * GENERATED by scripts/build-tokens-css.mjs from tokens/tokens.json — do not edit by hand.
 * Token set status: ${tokens.$meta.status.toUpperCase()}
 */`;
const css = `${header}\n:root {\n${lines.join('\n')}\n}\n`;
const cssPath = jsonPath.replace(/\.json$/, '.css');
writeFileSync(cssPath, css);
console.log(`wrote ${cssPath} (${lines.length} properties, status: ${tokens.$meta.status})`);
