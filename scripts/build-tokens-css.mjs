// tokens/tokens.json (source of truth) ->
//   tokens/tokens.css    CSS custom properties (--tb-*), each with a provenance comment
//   tokens/tailwind.css  Tailwind v4 `@theme inline` mapping, so apps get utilities such as
//                        bg-tb-action-primary-bg, text-tb-h1, rounded-tb-card, shadow-tb-modal
import { readFileSync, writeFileSync } from 'node:fs';

const jsonPath = process.env.TB_TOKENS_JSON ?? new URL('../tokens/tokens.json', import.meta.url).pathname;
const tokens = JSON.parse(readFileSync(jsonPath, 'utf8'));
const lines = [];
const tailwind = [];

// Tailwind v4 theme namespaces per token group. Groups without a namespace (space, breakpoint,
// layout, effect) stay CSS-variable only: use them as p-(--tb-space-4) etc.
function twName(path) {
  const [group, sub, ...rest] = path;
  const tail = (parts) => parts.join('-');
  if (group === 'color') return `--color-tb-${tail([sub, ...rest])}`;
  if (group === 'radius') return `--radius-tb-${tail([sub, ...rest])}`;
  if (group === 'shadow') return `--shadow-tb-${tail([sub, ...rest])}`;
  if (group === 'font' && sub === 'family') return `--font-tb-${tail(rest)}`;
  if (group === 'font' && sub === 'size') return `--text-tb-${tail(rest)}`;
  if (group === 'font' && sub === 'weight') return `--font-weight-tb-${tail(rest)}`;
  if (group === 'font' && sub === 'line-height') return `--leading-tb-${tail(rest)}`;
  return null;
}

function walk(node, path) {
  for (const [key, val] of Object.entries(node)) {
    if (key.startsWith('$') || typeof val !== 'object' || val === null) continue;
    if ('$value' in val) {
      const name = `--tb-${[...path, key].join('-')}`;
      const provenance = val.$observed ? `observed: ${val.$source}` : 'PLACEHOLDER — not observed';
      // $fallback (font stacks) is appended so apps without the licensed font degrade gracefully.
      const value = val.$fallback ? `${val.$value}, ${val.$fallback}` : val.$value;
      lines.push(`  ${name}: ${value}; /* ${provenance}${val.$fallback ? '; fallback appended (not observed)' : ''} */`);
      const tw = twName([...path, key]);
      if (tw) tailwind.push(`  ${tw}: var(${name});`);
    } else {
      walk(val, [...path, key]);
    }
  }
}
walk(tokens, []);

const header = `/*
 * GENERATED by scripts/build-tokens-css.mjs from tokens/tokens.json — do not edit by hand.
 * Token set status: ${tokens.$meta.status.toUpperCase()}
 */`;
const css = `${header}\n:root {\n${lines.join('\n')}\n}\n`;
const cssPath = jsonPath.replace(/\.json$/, '.css');
writeFileSync(cssPath, css);
const twPath = cssPath.replace(/tokens\.css$/, 'tailwind.css');
writeFileSync(twPath, `/*
 * GENERATED by scripts/build-tokens-css.mjs from tokens/tokens.json — do not edit by hand.
 * Tailwind v4 theme mapping. Import AFTER tailwindcss and the design system styles:
 *   @import "tailwindcss";
 *   @import "tailor-brands-design-system/styles.css";
 *   @import "tailor-brands-design-system/tailwind.css";
 * \`inline\` keeps utilities pointing at the --tb-* variables, so re-capturing tokens restyles them.
 * Token set status: ${tokens.$meta.status.toUpperCase()}
 */
@theme inline {
${tailwind.join('\n')}
}
`);
console.log(`wrote ${cssPath} (${lines.length} properties, status: ${tokens.$meta.status}) + ${twPath} (${tailwind.length} Tailwind theme variables)`);
